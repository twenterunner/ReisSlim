import { mkdir, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { tmpdir } from 'node:os';
import { pathToFileURL } from 'node:url';
import { CATALOGUE_MANIFEST, loadCountryPack, SUPPORTED_COUNTRY_CODES } from '../catalog-index.js';
import {
  DEFAULT_OVERPASS_ENDPOINT, OSM_ENRICHMENT_SCHEMA_VERSION, boundingBoxForBase,
  buildOverpassQuery, cachePathFor, enrichmentCacheIdentity, fetchOverpassJson,
  mergePackEnrichments, parseOverpassResponse, readCachedEnrichment, runBounded,
  selectImportantBases, writeCachedEnrichment
} from './osm-enrichment.mjs';

const ROOT = resolve(import.meta.dirname, '..');
const CACHE_ROOT = process.env.REISSLIM_OVERPASS_CACHE || join(tmpdir(), 'reisslim-overpass-cache');
const args = new Map(process.argv.slice(2).map(argument => {
  const [key, ...rest] = argument.replace(/^--/, '').split('=');
  return [key, rest.length ? rest.join('=') : true];
}));
const endpoint = String(args.get('endpoint') || process.env.REISSLIM_OVERPASS_ENDPOINT || DEFAULT_OVERPASS_ENDPOINT);
const fetchEnabled = args.has('fetch');
const applyEnabled = args.has('apply');
const refresh = args.has('refresh');
const allowPartial = args.has('allow-partial');
const concurrency = Number(args.get('concurrency') || 1);
const minimumDelayMs = Number(args.get('minimum-delay-ms') || 1200);
const radiusKm = Number(args.get('radius-km') || 12);
const explicitMaximum = args.has('bases-per-country') ? Number(args.get('bases-per-country')) : null;
const requestedCodes = String(args.get('countries') || '').split(',').map(code => code.trim().toUpperCase()).filter(Boolean);
const countryCodes = requestedCodes.length ? requestedCodes : SUPPORTED_COUNTRY_CODES;

for (const code of countryCodes) {
  if (!CATALOGUE_MANIFEST[code]) throw new Error(`Unsupported catalogue country code: ${code}`);
}
if (applyEnabled && !fetchEnabled && !args.has('cache-only')) {
  throw new Error('--apply without --fetch requires --cache-only to make the no-network behavior explicit');
}
if (concurrency > 2 && endpoint === DEFAULT_OVERPASS_ENDPOINT) {
  throw new Error('The public Overpass endpoint is capped at concurrency 2; use a private endpoint for higher concurrency');
}

function packModule(pack) {
  return `// Generated by scripts/generate-catalog.mjs and enriched by scripts/enrich-catalog-osm.mjs. GeoNames CC BY 4.0; OpenStreetMap ODbL 1.0. Do not edit manually.\nexport const COUNTRY_PACK = Object.freeze(${JSON.stringify(pack)});\nexport default COUNTRY_PACK;\n`;
}

async function taskFor(pack, base) {
  const query = buildOverpassQuery(base, { radiusKm });
  const identity = enrichmentCacheIdentity({ endpoint, base, query });
  const cachePath = cachePathFor(CACHE_ROOT, pack.country.code, base.id, identity);
  return { pack, base, query, identity, cachePath, bounds: boundingBoxForBase(base, radiusKm) };
}

async function loadOrFetch(task) {
  if (!refresh) {
    const cached = await readCachedEnrichment(task.cachePath);
    if (cached) return { ...task, enrichment: cached.enrichment, cache: 'hit', bytes: cached.rawBytes || null };
  }
  if (!fetchEnabled) return { ...task, enrichment: null, cache: 'miss', bytes: null };
  const startedAt = Date.now();
  const payload = await fetchOverpassJson(task.query, { endpoint });
  const retrievedAt = new Date().toISOString();
  const raw = JSON.stringify(payload);
  const enrichment = parseOverpassResponse(payload, task.base, {
    endpoint, retrievedAt, queryBounds: task.bounds
  });
  await writeCachedEnrichment(task.cachePath, {
    schemaVersion: OSM_ENRICHMENT_SCHEMA_VERSION,
    identity: task.identity,
    endpoint,
    query: task.query,
    queryBounds: task.bounds,
    retrievedAt,
    elapsedMs: Date.now() - startedAt,
    rawBytes: Buffer.byteLength(raw),
    rawResponse: payload,
    enrichment
  });
  return { ...task, enrichment, cache: 'fetched', bytes: Buffer.byteLength(raw) };
}

const packs = [];
const tasks = [];
for (const code of countryCodes) {
  const pack = structuredClone(await loadCountryPack(code));
  packs.push(pack);
  const bases = selectImportantBases(pack, explicitMaximum);
  for (const base of bases) tasks.push(await taskFor(pack, base));
  console.log(`${code}: planned ${bases.length} important-base queries`);
}

if (!fetchEnabled && !applyEnabled) {
  const summary = {
    schemaVersion: OSM_ENRICHMENT_SCHEMA_VERSION,
    endpoint,
    cacheRoot: CACHE_ROOT,
    countries: countryCodes.length,
    queries: tasks.length,
    radiusKm,
    concurrency,
    minimumDelayMs,
    note: 'Plan only. Add --fetch to populate the external raw cache; add --apply to rewrite country packs.'
  };
  console.log(JSON.stringify(summary, null, 2));
  process.exit(0);
}

const results = await runBounded(tasks, async task => {
  try {
    const result = await loadOrFetch(task);
    console.log(`${task.pack.country.code} ${task.base.name}: ${result.cache}${result.bytes ? `, ${result.bytes} bytes` : ''}`);
    return result;
  } catch (error) {
    console.error(`${task.pack.country.code} ${task.base.name}: ${error.message}`);
    return { ...task, enrichment: null, cache: 'error', error: error.message };
  }
}, { concurrency, minimumDelayMs });

const missing = results.filter(result => !result.enrichment);
if (missing.length && !allowPartial) {
  throw new Error(`${missing.length}/${results.length} enrichment responses unavailable; packs were not changed. Retry or pass --allow-partial explicitly.`);
}

if (applyEnabled) {
  for (const pack of packs) {
    const enrichments = results.filter(result => result.pack.country.code === pack.country.code).map(result => result.enrichment).filter(Boolean);
    const enriched = mergePackEnrichments(pack, enrichments);
    await writeFile(join(ROOT, `catalog-${pack.country.code.toLowerCase()}.js`), packModule(enriched), 'utf8');
    console.log(`${pack.country.code}: wrote ${enrichments.length} enriched bases, ${enriched.stats.namedRecommendations} named recommendations`);
  }
}

await mkdir(CACHE_ROOT, { recursive: true });
const report = {
  schemaVersion: OSM_ENRICHMENT_SCHEMA_VERSION,
  generatedAt: new Date().toISOString(),
  endpoint,
  cacheRoot: CACHE_ROOT,
  countries: countryCodes.length,
  plannedQueries: tasks.length,
  complete: results.filter(result => result.enrichment).length,
  missing: missing.length,
  fetched: results.filter(result => result.cache === 'fetched').length,
  cacheHits: results.filter(result => result.cache === 'hit').length,
  rawBytes: results.reduce((sum, result) => sum + (result.bytes || 0), 0),
  applied: applyEnabled
};
await writeFile(join(CACHE_ROOT, `report-${Date.now()}.json`), `${JSON.stringify(report, null, 2)}\n`, 'utf8');
console.log(JSON.stringify(report, null, 2));

// Keep the module importable by smoke tests without relying on process.cwd().
export const scriptUrl = pathToFileURL(import.meta.filename).href;

