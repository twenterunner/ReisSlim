export const CATALOG_LOCATOR_SCHEMA_VERSION = 1;

export function normalizeLocatorText(value = '') {
  return String(value).normalize('NFKD').toLocaleLowerCase('en')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[^\p{L}\p{N}]+/gu, ' ').trim();
}

function compactCoordinate(value) {
  return Math.round(Number(value) * 100000) / 100000;
}

function compactTerms(anchor) {
  return [...new Set([
    anchor.name,
    anchor.localName,
    ...(anchor.aliases || []),
    anchor.adminRegion
  ].map(normalizeLocatorText).filter(term => term.length >= 2))];
}

export function buildCatalogLocator(packs, catalogVersion) {
  const records = [];
  for (const pack of packs || []) {
    for (const anchor of pack?.anchors || []) {
      if (!anchor?.id || !anchor?.name || !Number.isFinite(Number(anchor.lat)) || !Number.isFinite(Number(anchor.lon))) continue;
      const terms = compactTerms(anchor);
      if (!terms.length) continue;
      records.push([
        pack.country.code,
        String(anchor.id),
        String(anchor.name),
        compactCoordinate(anchor.lat),
        compactCoordinate(anchor.lon),
        String(anchor.role || 'touring-anchor'),
        Math.round(Number(anchor.significance?.score || 0)),
        anchor.adminRegion ? String(anchor.adminRegion) : null,
        terms
      ]);
    }
  }
  records.sort((left, right) => left[0].localeCompare(right[0], 'en') || right[6] - left[6] || left[2].localeCompare(right[2], 'en'));
  return {
    schemaVersion: CATALOG_LOCATOR_SCHEMA_VERSION,
    catalogVersion,
    generatedAt: new Date().toISOString().slice(0, 10),
    source: {
      provider: 'GeoNames-derived ReisSlim touring catalogue',
      license: 'CC BY 4.0',
      url: 'https://www.geonames.org/',
      note: 'Compact lookup records are derived only from generated country-pack anchor names, aliases, administrative-region values and coordinates.'
    },
    records
  };
}

export function catalogLocatorModule(locator) {
  return `// Generated by the ReisSlim catalogue generation scripts from source-backed country packs. Do not edit manually.\nexport const CATALOG_LOCATOR = Object.freeze(${JSON.stringify(locator)});\nexport default CATALOG_LOCATOR;\n`;
}
